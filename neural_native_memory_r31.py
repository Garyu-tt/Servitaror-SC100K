C=r'''
typedef unsigned char u8;
typedef signed char i8;
typedef unsigned int u32;
static int fire(int x){return x>=33?5:0;}
/* weights generated by Selector.matrix; evaluate every local output. */
static int half(u32 a,int bits,const i8*w,int en,int*lo,int*hi){
 int n=1<<bits,ct=0;
 for(int r=0;r<n;r++){
   int c[2]={0,0};
   for(int rail=0;rail<2;rail++)for(int j=0;j<bits;j++)
     c[rail]+=5*w[(r*2+rail)*bits*2+2*j+((a>>j)&1)];
   lo[r]=fire(en*c[0]);hi[r]=fire(en*c[1]);
   if(lo[r]+hi[r]!=5)return -1;
   ct+=hi[r]==5;
 }
 return ct==1?0:-1;
}
int select_row(u32 a,int l,int h,const i8*w0,const i8*w1,int en){
 int al[128],ah[128],bl[128],bh[128],out=-1;
 if(l>7||h>7||l<1||h<1)return -1;
 if(half(a,l,w0,en,al,ah)||half(a>>l,h,w1,en,bl,bh))return -1;
 for(int y=0;y<(1<<h);y++)for(int x=0;x<(1<<l);x++){
   int low=fire(7*(al[x]+bl[y])),high=fire(4*(ah[x]+bh[y]));
   if(low+high!=5)return -1;
   if(high){if(out>=0)return -1;out=(y<<l)+x;}
 }
 return out;
}
static int rails(u8 w,int *l,int*h){
 *l=fire(5*(w&15));*h=fire(5*(w>>4));
 return *l+*h==5?0:-1;
}
int read_row(const u8*w,int col,int cols,u32*out){
 int sum[32][2]={{0}};u32 v=0;
 for(int j=0;j<cols;j++)for(int k=0;k<32;k++){
   int l,h;if(rails(w[j*32+k],&l,&h))return -1;
   sum[k][0]+=fire(4*(l+5*(j==col)));
   sum[k][1]+=fire(4*(h+5*(j==col)));
 }
 for(int k=0;k<32;k++){
   int l=fire(7*sum[k][0]),h=fire(7*sum[k][1]);
   if(l+h!=5)return -1;
   v|=(u32)(h==5)<<k;
 }
 *out=v;return 0;
}
int write_row(u8*w,int col,int cols,u32 v){
 u8 next[64*32];if(cols>64)return -1;
 for(int j=0;j<cols;j++)for(int k=0;k<32;k++){
   int l,h;if(rails(w[j*32+k],&l,&h))return -1;
   int sel=5*(j==col),hold=5-sel,d=5*((v>>k)&1);
   int nl=fire(7*(fire(4*(l+hold))+fire(4*(5-d+sel))));
   int nh=fire(7*(fire(4*(h+hold))+fire(4*(d+sel))));
   if(nl+nh!=5)return -1;
   next[j*32+k]=nh?0x71:0x17;
 }
 for(int j=0;j<cols*32;j++)w[j]=next[j];return 0;
}
'''
class Native:
    def __init__(self,a):
        root=a.build_dir;root.mkdir(parents=True,exist_ok=True)
        k=hashlib.sha256(C.encode()).hexdigest()[:20];c=root/(k+'.c');o=root/(k+'.o');so=root/(k+'.so');c.write_text(C)
        if a.ld:
            subprocess.run([a.cc,'-c','-o',str(o),str(c)],check=True)
            subprocess.run([a.ld,'-shared','-z','noexecstack','-o',str(so),str(o)],check=True)
        else:subprocess.run([a.cc,'-O3','-fPIC','-shared','-Wl,-z,noexecstack','-o',str(so),str(c)],check=True)
        self.lib=ctypes.CDLL(str(so.resolve()));ptr=ctypes.c_void_p;u=ctypes.c_uint32;i=ctypes.c_int
        self.sel=self.lib.select_row;self.sel.argtypes=[u,i,i,ptr,ptr,i];self.sel.restype=i
        self.rd=self.lib.read_row;self.rd.argtypes=[ptr,i,i,ctypes.POINTER(u)];self.rd.restype=i
        self.wr=self.lib.write_row;self.wr.argtypes=[ptr,i,i,u];self.wr.restype=i
    def select(self,s,a,ablate=False):
        if type(a) is not int or not 0<=a<s.n:raise ValueError('address')
        r=self.sel(a,s.low,s.high,s.weights[0].ctypes.data,s.weights[1].ctypes.data,int(not ablate))
        if r<0:raise RuntimeError('invalid route spikes')
        return r
    def attach(self,m):
        def route(a,ablate):
            if type(a) is not int or not 0<=a<m.n:raise ValueError('address')
            p,o=divmod(a,m.rows*m.cols);r,c=divmod(o,m.cols)
            return m.weights[self.select(m.bank,p,ablate),self.select(m.row,r,ablate)],self.select(m.col,c,ablate)
        def read(a,ablate=False):
            row,c=route(a,ablate);v=ctypes.c_uint32()
            if self.rd(row.ctypes.data,c,m.cols,ctypes.byref(v)):raise RuntimeError('invalid memory rails')
            m.reads+=1;return v.value
        def write(a,v,ablate=False):
            row,c=route(a,ablate)
            if self.wr(row.ctypes.data,c,m.cols,v&0xffffffff):raise RuntimeError('invalid memory rails')
            m.writes+=1
        m.read=read;m.write=write;m.program=write
def test(a):
    t=time.perf_counter();native=Native(a);ref=PagedCrossbar(8,rows=1024);m=PagedCrossbar(8,rows=1024)
    native.attach(m);rng=random.Random(310505);checks=0
    for s in (m.bank,m.row,m.col):
        for i in range(s.n):
            assert native.select(s,i)==int(np.flatnonzero(votes(s.select(i))[:,1]==5)[0]);checks+=1
    addrs=[0,63,64,65535,65536,m.n-1]+[rng.randrange(m.n) for _ in range(512)]
    for i in addrs:
        v=rng.getrandbits(32);ref.write(i,v);m.write(i,v)
        assert m.read(i)==ref.read(i)==v
    for i in addrs:assert m.read(i)==ref.read(i)
    assert np.array_equal(m.weights,ref.weights)
    before=m.weights.copy()
    for f in (lambda:m.read(0,True),lambda:m.write(0,9,True)):
        try:f()
        except RuntimeError:pass
        else:raise AssertionError('ablation')
    assert np.array_equal(before,m.weights)
    # Bad pair on an unselected column must still invalidate the row.
    m.weights[0,0,1,0]=0x77;before=m.weights[0,0].copy()
    for f in (lambda:m.read(0),lambda:m.write(0,5)):
        try:f()
        except RuntimeError:pass
        else:raise AssertionError('invalid rails')
    assert np.array_equal(before,m.weights[0,0])
    m.weights[0,0,1,0]=ref.weights[0,0,1,0]
    t0=time.perf_counter()
    for i in addrs:ref.read(i)
    old=time.perf_counter()-t0;t0=time.perf_counter()
    for i in addrs:m.read(i)
    new=time.perf_counter()-t0
    return dict(status='PASS',selector_checks=checks,read_comparisons=2*len(addrs),full_coefficients_equal=True,ablation_cases=2,corrupt_row_cases=2,reference_read_seconds=old,native_read_seconds=new,speedup=old/new,seconds=time.perf_counter()-t)
def run(a):
    data=a.image.read_bytes();h=hashlib.sha256(data).hexdigest();b=restore(data,a,a.input)
    n=Native(a);n.attach(b.memory);n.attach(b.disk);cache=PageCache(b);old=b.c.run;oldm=b.math.run;checks=0
    def ar(op,x,y,ablate=False):
        nonlocal checks
        v=old(op,x,y,ablate)
        if not ablate:assert v[0]==oracle(op,x,y);checks+=1
        return v
    def mr(op,x,y,ablate=False):
        nonlocal checks
        v=oldm(op,x,y,ablate)
        if not ablate:assert v==moracle(op,x,y);checks+=1
        return v
    b.c.run=ar;b.math.run=mr;before=(b.memory.reads,b.memory.writes)
    r=advance(b,a.steps);save(b,a.checkpoint,h)
    r.update(oracle_checks=checks,ram_read_delta=b.memory.reads-before[0],ram_write_delta=b.memory.writes-before[1],
        disk_reads=b.disk.reads,disk_writes=b.disk.writes,gpu_writes=b.gpu_writes,cache=cache.report(),
        no_guest_bytearray=b.ram is None,checkpoint_sha256=hashlib.sha256(a.checkpoint.read_bytes()).hexdigest())
    return r
def differential(a):
    data=a.image.read_bytes();h=hashlib.sha256(data).hexdigest();b=restore(data,a,a.input);q=restore(data,a,a.input)
    n=Native(a);n.attach(q.memory);n.attach(q.disk);PageCache(b);PageCache(q)
    r=advance(b,a.steps);s=advance(q,a.steps)
    assert r['delta']==s['delta'] and r['pc']==s['pc'] and r['fault']==s['fault']
    x=state(b,h);y=state(q,h);assert all(np.array_equal(x[k],y[k]) for k in x)
    return dict(status='PASS',reference=r,native=s,full_state_equal=True,speedup=r['seconds']/s['seconds'])
